export function normalizeVoronoiText(text: string): string {
  return text.replace(/[^A-Za-z]/g, "").toUpperCase();
}

export function normalizeVoronoiLayoutText(text: string): string {
  return text
    .replace(/\r\n|[\t\r\n]/g, " ")
    .replace(/[^A-Za-z ]/g, "")
    .toUpperCase();
}
