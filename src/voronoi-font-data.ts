import type { Point } from "./model";

export interface VoronoiGlyphData {
  sites: Point[];
  glyphCells: number[];
  sourceUrl: string;
}

function glyph(
  sites: Point[],
  glyphBits: string,
  sourceUrl: string,
): VoronoiGlyphData {
  return {
    sites,
    glyphCells: Array.from(glyphBits, (bit) => (bit === "1" ? 1 : 0)),
    sourceUrl,
  };
}

